#!/usr/bin/env python3
"""
Generate selection/include/ppfx_weights.h from the PPFX central-value flux
weight histograms in flux.root (the same file and histograms that
systematics/add_numi_flux_sys.py reads in stage 5):

    ppfx_flux_weights/hweights_<horn>_{numu,numubar,nue,nuebar}

The header holds the bin edges and weights as constexpr arrays, so the
selection can compute ppfx_cv_weight per interaction (mctruth variable
`ppfx_cv_weight`) without opening flux.root on the grid.

    python3 scripts/make_ppfx_header.py                # write the header
    python3 scripts/make_ppfx_header.py --check        # exit 1 if it is stale

Host python (uproot + numpy) is enough.
"""
import argparse
import hashlib
import sys
from pathlib import Path

import numpy as np
import uproot

REPO = Path(__file__).resolve().parent.parent
DEFAULT_FLUX = '/nashome/m/micarrig/icarus/nuESpine/flux.root'
DEFAULT_OUT = REPO / 'selection' / 'include' / 'ppfx_weights.h'
FLAVORS = [('numu', 14), ('numubar', -14), ('nue', 12), ('nuebar', -12)]


def read_tables(flux_path, horn):
    """{flavor: (edges, values)} from the flux file."""
    tables = {}
    with uproot.open(flux_path) as f:
        for flavor, _ in FLAVORS:
            h = f[f'ppfx_flux_weights/hweights_{horn}_{flavor}']
            tables[flavor] = check_binning(flavor, h.axes[0].edges(), h.values())
    return tables


def check_binning(flavor, edges, values):
    edges, values = np.asarray(edges, dtype=float), np.asarray(values, dtype=float)
    if len(edges) != len(values) + 1 or np.any(np.diff(edges) <= 0):
        raise ValueError(f'{flavor}: bad binning {edges}')
    return edges, values


def _array(name, xs):
    body = ', '.join(repr(float(x)) for x in xs)
    return f'    inline constexpr double {name}[{len(xs)}] = {{ {body} }};\n'


def render(tables, flux_path, horn, digest):
    out = [
        '/**\n',
        ' * @file ppfx_weights.h\n',
        ' * @brief PPFX central-value flux weights per neutrino flavor and true energy.\n',
        ' * @details GENERATED by scripts/make_ppfx_header.py -- do not edit by hand.\n',
        f' * Source: {flux_path} (md5 {digest}),\n',
        f' * histograms ppfx_flux_weights/hweights_{horn}_{{numu,numubar,nue,nuebar}}.\n',
        ' * Bins are [low, high) in GeV; energies outside the histogram range get weight 1.\n',
        ' */\n',
        '#ifndef PPFX_WEIGHTS_H\n',
        '#define PPFX_WEIGHTS_H\n',
        '#include <algorithm>\n',
        '#include <cmath>\n',
        '#include <cstddef>\n',
        '\n',
        'namespace ppfx\n',
        '{\n',
        f'    inline constexpr const char * kHornCurrent = "{horn}";\n',
    ]
    for flavor, _ in FLAVORS:
        edges, values = tables[flavor]
        out.append('\n')
        out.append(_array(f'{flavor}_edges', edges))
        out.append(_array(f'{flavor}_weights', values))
    out.append('''
    /**
     * @brief Weight of the bin containing @p energy ([low, high) bins).
     * @return 1 if @p energy is not finite or outside [edges[0], edges[n]).
     */
    template<std::size_t N>
    inline double lookup(const double (&edges)[N], const double (&weights)[N - 1], double energy)
    {
        if(!std::isfinite(energy) || energy < edges[0] || energy >= edges[N - 1])
            return 1.0;
        const double * it = std::upper_bound(edges, edges + N, energy);
        return weights[(it - edges) - 1];
    }

    /**
     * @brief PPFX central-value weight for a neutrino of PDG code @p pdg and
     * true energy @p energy (GeV). 1 for any other PDG code.
     */
    inline double cv_weight(int pdg, double energy)
    {
        switch(pdg)
        {
''')
    for flavor, code in FLAVORS:
        out.append(f'            case {code}: return lookup({flavor}_edges, {flavor}_weights, energy);\n')
    out.append('''            default: return 1.0;
        }
    }
} // namespace ppfx
#endif // PPFX_WEIGHTS_H
''')
    return ''.join(out)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--flux', default=DEFAULT_FLUX, help=f'flux file (default {DEFAULT_FLUX})')
    p.add_argument('--horn', default='fhc', choices=['fhc', 'rhc'])
    p.add_argument('--output', type=Path, default=DEFAULT_OUT)
    p.add_argument('--check', action='store_true', help='compare with the existing header, write nothing')
    a = p.parse_args(argv)
    digest = hashlib.md5(Path(a.flux).read_bytes()).hexdigest()
    text = render(read_tables(a.flux, a.horn), a.flux, a.horn, digest)
    if a.check:
        same = a.output.exists() and a.output.read_text() == text
        print(f'{a.output}: {"up to date" if same else "STALE (rerun without --check)"}')
        return 0 if same else 1
    a.output.write_text(text)
    print(f'wrote {a.output}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
